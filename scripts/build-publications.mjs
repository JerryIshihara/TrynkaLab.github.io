import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import matter from 'gray-matter';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicationDirectory = path.join(repositoryRoot, 'publications');
const generatedDirectory = path.join(repositoryRoot, 'theme', 'generated');
const generatedFile = path.join(generatedDirectory, 'publications.ts');

const requiredTextFields = ['title', 'date', 'venue', 'type', 'url'];
const optionalTextFields = ['citation', 'codeUrl', 'doi'];
const publicationTypes = new Set(['article', 'preprint']);

function fail(fileName, message) {
  throw new Error(`publications/${fileName}: ${message}`);
}

function textField(data, field, fileName, required = true) {
  const value = data[field];
  if (value === undefined && !required) return undefined;
  if (typeof value !== 'string' || value.trim() === '') {
    fail(fileName, `frontmatter field "${field}" must be a non-empty string`);
  }
  return value.trim();
}

function validUrl(value, field, fileName) {
  if (value === undefined) return;

  try {
    new URL(value);
  } catch {
    fail(fileName, `frontmatter field "${field}" must be an absolute URL`);
  }
}

async function readPublication(fileName) {
  const source = await readFile(path.join(publicationDirectory, fileName), 'utf8');
  const { content, data } = matter(source);

  for (const field of requiredTextFields) {
    textField(data, field, fileName);
  }

  if (!Number.isInteger(data.year)) {
    fail(fileName, 'frontmatter field "year" must be an integer');
  }
  if (!Array.isArray(data.authors) || data.authors.length === 0) {
    fail(fileName, 'frontmatter field "authors" must be a non-empty list');
  }
  if (data.authors.some((author) => typeof author !== 'string' || author.trim() === '')) {
    fail(fileName, 'every author must be a non-empty string');
  }
  if (!publicationTypes.has(data.type)) {
    fail(fileName, 'frontmatter field "type" must be "article" or "preprint"');
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date)) {
    fail(fileName, 'frontmatter field "date" must use YYYY-MM-DD');
  }

  const optionalFields = Object.fromEntries(
    optionalTextFields
      .map((field) => [field, textField(data, field, fileName, false)])
      .filter(([, value]) => value !== undefined),
  );
  validUrl(data.url, 'url', fileName);
  validUrl(optionalFields.codeUrl, 'codeUrl', fileName);

  return {
    id: path.basename(fileName, '.md'),
    title: data.title.trim(),
    authors: data.authors.map((author) => author.trim()),
    year: data.year,
    date: data.date.trim(),
    venue: data.venue.trim(),
    type: data.type,
    url: data.url.trim(),
    ...optionalFields,
    summary: content.trim().replace(/\s+/g, ' '),
  };
}

const fileNames = (await readdir(publicationDirectory))
  .filter((fileName) => fileName.endsWith('.md'))
  .filter((fileName) => fileName !== 'README.md' && !fileName.startsWith('_'));

const publications = await Promise.all(fileNames.map(readPublication));
publications.sort((left, right) => right.date.localeCompare(left.date));

const generatedSource = `// Generated by scripts/build-publications.mjs. Do not edit directly.\n\nexport interface Publication {\n  id: string;\n  title: string;\n  authors: string[];\n  year: number;\n  date: string;\n  venue: string;\n  type: 'article' | 'preprint';\n  url: string;\n  citation?: string;\n  codeUrl?: string;\n  doi?: string;\n  summary: string;\n}\n\nexport const publications: readonly Publication[] = ${JSON.stringify(publications, null, 2)};\n`;

await mkdir(generatedDirectory, { recursive: true });
await writeFile(generatedFile, generatedSource, 'utf8');

console.log(`Loaded ${publications.length} publications from publications/*.md`);
